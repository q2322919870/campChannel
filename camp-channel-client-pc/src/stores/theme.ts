const themes: Theme[] = rawThemes.map(enrichTheme)

export const useThemeStore = defineStore('theme', () => {
  const savedIndex = parseInt(localStorage.getItem('themeIndex') || '0')
  const themeIndex = ref(savedIndex >= 0 && savedIndex < themes.length ? savedIndex : 0)

  const currentTheme = computed(() => themes[themeIndex.value])
  const themeList = computed(() => themes)

  function setTheme(index: number) {
    if (index >= 0 && index < themes.length) {
      themeIndex.value = index
      localStorage.setItem('themeIndex', String(index))
      applyTheme()
      // Update cursor effects
      setCursorTheme(index)
    }
  }

  function applyTheme() {
    const t = currentTheme.value
    const root = document.documentElement
    root.style.setProperty('--primary', t.primary)
    root.style.setProperty('--primary-container', t.primaryContainer)
    root.style.setProperty('--on-primary-container', t.onPrimaryContainer)
    root.style.setProperty('--secondary', t.secondary)
    root.style.setProperty('--secondary-container', t.secondaryContainer)
    root.style.setProperty('--tertiary', t.tertiary)
    root.style.setProperty('--tertiary-container', t.tertiaryContainer)
    root.style.setProperty('--surface', t.surface)
    root.style.setProperty('--surface-variant', t.surfaceVariant)
    root.style.setProperty('--surface-tint', t.surfaceTint)
    root.style.setProperty('--background', t.background)
    root.style.setProperty('--on-surface', t.onSurface)
    root.style.setProperty('--on-surface-variant', t.onSurfaceVariant)
    root.style.setProperty('--outline', t.outline)
    root.style.setProperty('--outline-variant', t.outlineVariant)
    root.style.setProperty('--error', t.error)
    root.style.setProperty('--error-container', t.errorContainer)
    root.style.setProperty('--scrim', t.scrim)
    root.style.setProperty('--inverse-surface', t.inverseSurface)
    root.style.setProperty('--inverse-on-surface', t.inverseOnSurface)
    root.style.setProperty('--inverse-primary', t.inversePrimary)
    root.style.setProperty('--radius', t.borderRadius)
    root.style.setProperty('--card-radius', t.cardRadius)
    root.style.setProperty('--button-radius', t.buttonRadius)
    root.style.setProperty('--shadow', t.shadow)
    root.style.setProperty('--card-shadow', t.cardShadow)
    root.style.setProperty('--theme-style', t.style)
    root.style.setProperty('--brand', t.brand)
    root.style.setProperty('--brand-secondary', t.brandSecondary)
    root.style.setProperty('--card-bg', t.card)
    root.style.setProperty('--article-bg', t.article)
    root.style.setProperty('--border-color', t.border)
    root.style.setProperty('--text', t.text)
    root.classList.toggle('theme-dark', t.isDark)
    root.classList.toggle('theme-light', !t.isDark)
    setCursorTheme(themeIndex.value)
  }

  return { themeIndex, currentTheme, themeList, setTheme, applyTheme }
})
